// Converts the reverse-of-power Android vector drawables (ic_*.xml) into inline SVG
// strings for the web page. Usage: node tools/convert-drawables.mjs <path-to-res/drawable>
import fs from 'node:fs';
import path from 'node:path';

const srcDir = process.argv[2];
if (!srcDir) {
  console.error('Usage: node tools/convert-drawables.mjs <reverse-of-power/app/src/main/res/drawable>');
  process.exit(1);
}
const outFile = path.join(path.dirname(new URL(import.meta.url).pathname.replace(/^\/(\w:)/, '$1')), '..', 'src', 'web', 'generated', 'icons.js');

function attr(tag, name) {
  const m = tag.match(new RegExp(`android:${name}="([^"]*)"`));
  return m ? m[1] : null;
}

// Android colors are #RGB, #ARGB, #RRGGBB or #AARRGGBB.
function color(value) {
  if (!value || !value.startsWith('#')) return null;
  let hex = value.slice(1);
  if (hex.length === 3) hex = hex.split('').map((c) => c + c).join('');
  if (hex.length === 4) hex = hex.split('').map((c) => c + c).join('');
  if (hex.length === 6) return { rgb: `#${hex}`, alpha: 1 };
  const alpha = parseInt(hex.slice(0, 2), 16) / 255;
  return { rgb: `#${hex.slice(2)}`, alpha };
}

function convert(xml) {
  const vector = xml.match(/<vector[\s\S]*?>/)[0];
  const vw = attr(vector, 'viewportWidth');
  const vh = attr(vector, 'viewportHeight');
  const paths = [...xml.matchAll(/<path[\s\S]*?\/>/g)].map(([tag]) => {
    const d = attr(tag, 'pathData');
    const fill = color(attr(tag, 'fillColor'));
    const stroke = color(attr(tag, 'strokeColor'));
    const parts = [`d="${d}"`];
    if (fill && fill.alpha > 0) {
      parts.push(`fill="${fill.rgb}"`);
      const fillAlpha = Number(attr(tag, 'fillAlpha') ?? 1) * fill.alpha;
      if (fillAlpha < 1) parts.push(`fill-opacity="${+fillAlpha.toFixed(3)}"`);
    } else {
      parts.push('fill="none"');
    }
    if (stroke && stroke.alpha > 0) {
      parts.push(`stroke="${stroke.rgb}"`);
      if (stroke.alpha < 1) parts.push(`stroke-opacity="${+stroke.alpha.toFixed(3)}"`);
      parts.push(`stroke-width="${attr(tag, 'strokeWidth') || 1}"`);
      const cap = attr(tag, 'strokeLineCap');
      const join = attr(tag, 'strokeLineJoin');
      if (cap) parts.push(`stroke-linecap="${cap}"`);
      if (join) parts.push(`stroke-linejoin="${join}"`);
    }
    return `<path ${parts.join(' ')}/>`;
  });
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${vw} ${vh}">${paths.join('')}</svg>`;
}

const icons = {};
for (const file of fs.readdirSync(srcDir).filter((f) => /^ic_.*\.xml$/.test(f)).sort()) {
  const xml = fs.readFileSync(path.join(srcDir, file), 'utf8');
  if (!xml.includes('<vector')) continue;
  icons[file.replace(/^ic_/, '').replace(/\.xml$/, '')] = convert(xml);
}
fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, `// Generated by tools/convert-drawables.mjs from reverse-of-power (GPL-3.0). Do not edit.\nconst ICONS = ${JSON.stringify(icons, null, 1)};\n`);
console.log(`Wrote ${Object.keys(icons).length} icons to ${outFile}: ${Object.keys(icons).join(', ')}`);

const resDir = path.dirname(srcDir);
const unescape = (s) => s.replace(/\\'/g, "'").replace(/\\"/g, '"').replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>');
const factXml = fs.readFileSync(path.join(resDir, 'values', 'factoids.xml'), 'utf8');
const factoids = [...factXml.matchAll(/<item>([\s\S]*?)<\/item>/g)].map(([, t]) => unescape(t.trim()));
const stub = fs.readFileSync(path.join(resDir, 'raw', 'avatar_stub.jpeg')).toString('base64');
const dataFile = path.join(path.dirname(outFile), 'data.js');
fs.writeFileSync(dataFile, `// Generated by tools/convert-drawables.mjs from reverse-of-power (GPL-3.0). Do not edit.\nconst FACTOIDS = ${JSON.stringify(factoids)};\nconst AVATAR_STUB_JPEG = '${stub}';\n`);
console.log(`Wrote ${factoids.length} factoids and the placeholder photo to ${dataFile}`);
